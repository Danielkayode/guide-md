function generateFish(): string {
  return `# Fish completion for guidemd
# Generated by guidemd completion fish
# Place this file at ~/.config/fish/completions/guidemd.fish

function __guidemd_commands
  echo ${COMMAND_NAMES}
end

function __guidemd_global_flags
  echo ${GLOBAL_FLAGS.join(" ")}
end

function __guidemd_complete
  set -l cmd (commandline -opc)

  # Complete the first argument (the command)
  if test (count \$cmd) -eq 1
    __guidemd_commands | string match -- "*\$argv*"
    return
  end

  set -l subcommand \$cmd[2]

  # Complete global flags and subcommand-specific flags
  switch \$subcommand
    case lint export import doctor fix sync verify profile optimize info badge ci serve diff watch migrate check
      __guidemd_global_flags | string match -- "*\$argv*"
      if commandline -ct | string match -q -- '--*'
        echo --file --out --target --format --json --fix --sync --stats --skip-secret-scan --manifest --min-score --dry-run --force --write --readme --template --badge --port | string match -- "*\$argv*"
      end
    case init
      __guidemd_global_flags | string match -- "*\$argv*"
      echo --force | string match -- "*\$argv*"
    case add
      __guidemd_global_flags | string match -- "*\$argv*"
      echo --force | string match -- "*\$argv*"
    case completion help
      __guidemd_global_flags | string match -- "*\$argv*"
    case '*'
      __guidemd_global_flags | string match -- "*\$argv*"
  end
end

complete -c guidemd -f -a '(__guidemd_complete)'
`;
}

function generatePowerShell(): string {
  return `# PowerShell completion for guidemd
# Generated by guidemd completion powershell
# Add this to your PowerShell profile:
#   guidemd completion powershell | Out-String | Invoke-Expression

Register-ArgumentCompleter -Native -CommandName guidemd -ScriptBlock {
  param($WordToComplete, $CommandAst, $CursorPosition)

  $commands = @(${COMMANDS.map((c) => `'${c.name}'`).join(", ")})
  $globalFlags = @(${GLOBAL_FLAGS.map((f) => `'${f}'`).join(", ")})

  $astTokens = $CommandAst.FindAll({ $true }, $false)
  $positionalArgs = $astTokens | Where-Object { $_.Kind -eq 'CommandParameter' -or ($_.Kind -eq 'StringConstant' -and $_.Parent -isnot [System.Management.Automation.Language.CommandParameterAst]) }

  # If completing the command itself
  if ($WordToComplete -eq "" -or $astTokens.Count -le 1) {
    $commands | Where-Object { $_ -like "$WordToComplete*" } | ForEach-Object {
      [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
    return
  }

  # Determine the subcommand (second token)
  $subcommand = $null
  for ($i = 1; $i -lt $astTokens.Count; $i++) {
    $token = $astTokens[$i]
    if ($token.Text -and $commands -contains $token.Text) {
      $subcommand = $token.Text
      break
    }
  }

  if ($subcommand) {
    $flags = $globalFlags
    switch ($subcommand) {
      { "lint","export","import","doctor","fix","sync","verify","profile","optimize","info","badge","ci","serve","diff","watch","migrate","check" -contains $_ } {
        $flags += @("--file","--out","--target","--format","--json","--fix","--sync","--stats","--skip-secret-scan","--manifest","--min-score","--dry-run","--force","--write","--readme","--template","--badge","--port")
      }
      "init" { $flags += @("--force") }
      "add" { $flags += @("--force") }
    }

    $flags | Where-Object { $_ -like "$WordToComplete*" } | ForEach-Object {
      [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterName', $_)
    }
  }
}
`;
}
