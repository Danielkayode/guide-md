const COMMAND_NAMES = COMMANDS.map((c) => c.name).join(" ");
const COMMAND_LIST = COMMANDS.map((c) => `  ${c.name.padEnd(24)}${c.description}`).join("\n");

const GLOBAL_FLAGS = [
  "--help",
  "-h",
  "--version",
  "-V",
];

/** Generate a shell completion script for the given shell. */
export function generateCompletion(shell: CompletionShell): string {
  switch (shell) {
    case "bash":
      return generateBash();
    case "zsh":
      return generateZsh();
    case "fish":
      return generateFish();
    case "powershell":
      return generatePowerShell();
    default:
      throw new Error(`Unsupported shell: ${shell}`);
  }
}

